class SwitchExample2 {
    public static void main(String args[]) {
        int i = 1;

        switch(i) {
            case 0:
                System.out.println("i is zero");
                break;
            case 1:
                System.out.println("i is one");
                break;
            default:
                System.out.println("i is greater than one");
        }
    }
}
